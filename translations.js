// Функция переключения языка
function setLanguage(lang) {
  // Сохраняем выбор в localStorage
  localStorage.setItem('siteLang', lang);
  
  // Обновляем все элементы с data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = translations[lang]?.[key];
    if (translation) {
      // Если в переводе есть <br>, используем innerHTML, иначе textContent
      if (translation.includes('<br')) {
        el.innerHTML = translation;
      } else {
        el.textContent = translation;
      }
    }
  });
  
  // Обновляем ссылки (они тоже могут переводиться)
  document.querySelectorAll('[data-i18n-link]').forEach(el => {
    const key = el.getAttribute('data-i18n-link');
    const translation = translations[lang]?.[key];
    if (translation) {
      el.textContent = translation;
    }
  });
  
  // Визуально выделяем активный язык
  document.querySelector('.header_ru').style.opacity = lang === 'ru' ? '1' : '0.6';
  document.querySelector('.header_en').style.opacity = lang === 'en' ? '1' : '0.6';
}

// Инициализация при загрузке
document.addEventListener('DOMContentLoaded', () => {
  // Получаем язык из localStorage или используем 'ru' по умолчанию
  const savedLang = localStorage.getItem('siteLang') || 'ru';
  setLanguage(savedLang);
  
  // Навешиваем обработчики на кнопки
  document.querySelector('.header_ru').addEventListener('click', () => setLanguage('ru'));
  document.querySelector('.header_en').addEventListener('click', () => setLanguage('en'));
});
